/**
 * Recording a Transaksi Kas, and the property the whole spec rests on: the buku kas is append-only.
 * Against a real PostgreSQL, because "nothing that was committed ever changes" is a statement about
 * committed rows.
 *
 * Since #315 every row is written by one function, `writeCashTransaction` in
 * `src/lib/server/services/cash/writer.ts`, and the first describe below is where that is held: the
 * writer's exported surface, a parse of every source file for a second write statement, the rule
 * that only the dues module reaches the two Pembatalan kinds, and the witness that drives every kind.
 */

